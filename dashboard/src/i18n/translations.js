/** Resolve a dot-notation key like 'nav.home' for the given language */
export function t(lang, key) {
  const keys = key.split('.');
  let val = translations[lang] || translations.en;
  for (const k of keys) {
    val = val?.[k];
  }
  return val ?? key;
}
